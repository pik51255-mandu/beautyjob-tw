def render_question(q, lang):
    """문항 원문 — JSON 값만 사용한다."""
    marks = "①②③④"
    opts = " ".join(f"{m}{o}" for m, o in zip(marks, q["options"]))
    line = f"{q['stem']} {opts}".strip() if q["stem"] else opts
    line += f" {q['tail']}" if q["tail"] else " 。"
    ans_no = q["answer"]
    ans_txt = q["options"][ans_no - 1]
    label = "答" if lang == "zh" else "정답"
    return f"> {line}\n\n**{label}：{marks[ans_no - 1]}{ans_txt}**\n"


